function createBridge({ contextBridge: bridge, ipcRenderer: ipc }) {
  const api = Object.freeze({
    getSettings: () => ipc.invoke(CHANNELS.GET_SETTINGS),
    getAgentControl: () => ipc.invoke(CHANNELS.GET_AGENT_CONTROL),
    setAgentBackend: (backend) => ipc.invoke(CHANNELS.SET_AGENT_BACKEND, backend),
    getMcpConnection: () => ipc.invoke(CHANNELS.GET_MCP_CONNECTION),
    codexLogin: (input) => ipc.invoke(CHANNELS.CODEX_LOGIN, input),
    codexCancelLogin: (loginId) => ipc.invoke(CHANNELS.CODEX_CANCEL_LOGIN, loginId),
    codexLogout: () => ipc.invoke(CHANNELS.CODEX_LOGOUT),
    selectCodexModel: (model) => ipc.invoke(CHANNELS.SELECT_CODEX_MODEL, model),
    saveConnection: (input) => ipc.invoke(CHANNELS.SAVE_CONNECTION, input),
    removeConnection: (id) => ipc.invoke(CHANNELS.REMOVE_CONNECTION, id),
    selectModel: (input) => ipc.invoke(CHANNELS.SELECT_MODEL, input),
    getModelCatalog: () => ipc.invoke(CHANNELS.GET_MODEL_CATALOG),
    updateModel: (input) => ipc.invoke(CHANNELS.UPDATE_MODEL, input),
    checkModelCapabilities: (input) => ipc.invoke(CHANNELS.CHECK_MODEL_CAPABILITIES, input),
    openExternal: (url) => ipc.invoke(CHANNELS.OPEN_EXTERNAL, url),
    listCanvasFiles: (id) => ipc.invoke(CHANNELS.LIST_CANVAS_FILES, id),
    readCanvasFile: (id, input) => ipc.invoke(CHANNELS.READ_CANVAS_FILE, id, input),
    deleteProjectFile: (id, input) => ipc.invoke(CHANNELS.DELETE_PROJECT_FILE, id, input),
    deleteProject: (id) => ipc.invoke(CHANNELS.DELETE_PROJECT, id),
    deleteProjectAsset: (id, assetId) => ipc.invoke(CHANNELS.DELETE_PROJECT_ASSET, id, assetId),
    deleteLibraryAsset: (assetId) => ipc.invoke(CHANNELS.DELETE_LIBRARY_ASSET, assetId),
    createProject: (input) => ipc.invoke(CHANNELS.CREATE_PROJECT, input),
    renameProject: (id, input) => ipc.invoke(CHANNELS.RENAME_PROJECT, id, input),
    exportProject: (id) => ipc.invoke(CHANNELS.EXPORT_PROJECT, id),
    listProjectDocuments: (id) => ipc.invoke(CHANNELS.LIST_PROJECT_DOCUMENTS, id),
    createProjectDocument: (id, input) => ipc.invoke(CHANNELS.CREATE_PROJECT_DOCUMENT, id, input),
    openProjectDocument: (id, documentPath) => ipc.invoke(CHANNELS.OPEN_PROJECT_DOCUMENT, id, documentPath),
    getAvailableKits: () => ipc.invoke(CHANNELS.GET_AVAILABLE_KITS),
    getProjectKits: (id) => ipc.invoke(CHANNELS.GET_PROJECT_KITS, id),
    updateProjectKits: (id, input) => ipc.invoke(CHANNELS.UPDATE_PROJECT_KITS, id, input),
    getProjectAssets: (id, options) => ipc.invoke(CHANNELS.GET_PROJECT_ASSETS, id, ...(options === undefined ? [] : [options])),
    getProjectAsset: (id, assetId) => ipc.invoke(CHANNELS.GET_PROJECT_ASSET, id, assetId),
    getLibraryAsset: (assetId) => ipc.invoke(CHANNELS.GET_LIBRARY_ASSET, assetId),
    saveLibraryAsset: (assetId) => ipc.invoke(CHANNELS.SAVE_LIBRARY_ASSET, assetId),
    attachProjectAsset: (id, assetId) => ipc.invoke(CHANNELS.ATTACH_PROJECT_ASSET, id, assetId),
    saveProjectAsset: (id, assetId) => ipc.invoke(CHANNELS.SAVE_PROJECT_ASSET, id, assetId),
    hideCanvasPreview: () => ipc.invoke(CHANNELS.HIDE_CANVAS_PREVIEW),
    manageCanvasDevices: (id) => ipc.invoke(CHANNELS.MANAGE_CANVAS_DEVICES, id),
    closeCanvas: (id) => ipc.invoke(CHANNELS.CLOSE_CANVAS, id),
    listCanvasInputs: () => ipc.invoke(CHANNELS.LIST_CANVAS_INPUTS),
    retryCanvasInput: (id) => ipc.invoke(CHANNELS.RETRY_CANVAS_INPUT, id),
    listLiteLLMModels: () => ipc.invoke(CHANNELS.LIST_LITELLM_MODELS),
    testLiteLLMChat: (model) => ipc.invoke(CHANNELS.TEST_LITELLM_CHAT, model),
    testLiteLLMImage: (model) => ipc.invoke(CHANNELS.TEST_LITELLM_IMAGE, model),
    listInstalledSkills: () => ipc.invoke(CHANNELS.LIST_INSTALLED_SKILLS),
    saveSettings: (settings) => ipc.invoke(CHANNELS.SAVE_SETTINGS, settings),
    importMedia: (input = {}) => ipc.invoke(CHANNELS.IMPORT_MEDIA, input),
    listTemplates: (input = {}) => ipc.invoke(CHANNELS.LIST_TEMPLATES, input),
    createTemplateInstance: (input) => ipc.invoke(CHANNELS.CREATE_TEMPLATE_INSTANCE, input),
    openTemplateInstance: (input) => ipc.invoke(CHANNELS.OPEN_TEMPLATE_INSTANCE, input),
    openVideoEditor: (input = {}) => ipc.invoke(CHANNELS.OPEN_VIDEO_EDITOR, input),
    readTimeline: (id, timelineId) => ipc.invoke(CHANNELS.READ_TIMELINE, id, timelineId),
    createTimeline: (id, timelineId, input) => ipc.invoke(CHANNELS.CREATE_TIMELINE, id, timelineId, input),
    applyTimeline: (id, timelineId, input) => ipc.invoke(CHANNELS.APPLY_TIMELINE, id, timelineId, input),
    undoTimeline: (id, timelineId, input) => ipc.invoke(CHANNELS.UNDO_TIMELINE, id, timelineId, input),
    redoTimeline: (id, timelineId, input) => ipc.invoke(CHANNELS.REDO_TIMELINE, id, timelineId, input),
    getTimelineHistory: (id, timelineId) => ipc.invoke(CHANNELS.TIMELINE_HISTORY, id, timelineId),
    sendMessage: (text, options) => ipc.invoke(CHANNELS.SEND_MESSAGE, text, options),
    stopAgent: () => ipc.invoke(CHANNELS.STOP_AGENT),
    clearChat: () => ipc.invoke(CHANNELS.CLEAR_CHAT),
    getCurrentChat: (options) => ipc.invoke(CHANNELS.GET_CHAT, ...(options === undefined ? [] : [options])),
    acknowledgeChat: (id) => ipc.invoke(CHANNELS.ACKNOWLEDGE_CHAT, id),
    listChats: () => ipc.invoke(CHANNELS.LIST_CHATS),
    openChat: (id) => ipc.invoke(CHANNELS.OPEN_CHAT, id),
    listAssets: () => ipc.invoke(CHANNELS.LIST_ASSETS),
    listMediaJobs: () => ipc.invoke(CHANNELS.LIST_MEDIA_JOBS),
    deleteMediaJob: (id) => ipc.invoke(CHANNELS.DELETE_MEDIA_JOB, id),
    retryMediaJob: (id) => ipc.invoke(CHANNELS.RETRY_MEDIA_JOB, id),
    listCanvases: () => ipc.invoke(CHANNELS.LIST_CANVASES),
    createCanvas: (title, kits = []) => ipc.invoke(CHANNELS.CREATE_CANVAS, title, kits),
    openCanvas: (id) => ipc.invoke(CHANNELS.OPEN_CANVAS, id),
    saveCanvas: (id) => ipc.invoke(CHANNELS.SAVE_CANVAS, id),
    exportCanvas: (id) => ipc.invoke(CHANNELS.EXPORT_CANVAS, id),
    addAssetToCanvas: (id, options) => ipc.invoke(CHANNELS.ADD_ASSET_TO_CANVAS, id, options),
    undoCanvas: (id) => ipc.invoke(CHANNELS.UNDO_CANVAS, id),
    setCanvasBounds: (bounds) => ipc.send(CHANNELS.SET_CANVAS_BOUNDS, bounds),
    onAgentEvent(callback) {
      if (typeof callback !== 'function') throw new TypeError('Event callback must be a function.');
      const listener = (_event, payload) => callback(payload);
      ipc.on(CHANNELS.AGENT_EVENT, listener);
      return () => ipc.removeListener(CHANNELS.AGENT_EVENT, listener);
    },
  });

  bridge.exposeInMainWorld('easelClient', api);
  return api;
}

createBridge({ contextBridge, ipcRenderer });

module.exports = { createBridge };

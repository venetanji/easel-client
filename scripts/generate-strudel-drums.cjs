const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

// Original, deterministic electronic one-shots. No third-party recordings.
function generateDrumBank() {
  const rate = 48000;
  const definitions = [
    ['bd', 'Kick', 0.45], ['sd', 'Snare', 0.25], ['hh', 'Closed hat', 0.09],
    ['oh', 'Open hat', 0.5], ['cp', 'Clap', 0.28], ['tom', 'Tom', 0.4], ['rim', 'Rim', 0.09],
  ];
  const samples = definitions.map(([name, label, durationSeconds], index) => {
    const frames = Math.round(durationSeconds * rate), bytes = Buffer.alloc(44 + frames * 2);
    bytes.write('RIFF'); bytes.writeUInt32LE(bytes.length - 8, 4); bytes.write('WAVEfmt ', 8);
    bytes.writeUInt32LE(16, 16); bytes.writeUInt16LE(1, 20); bytes.writeUInt16LE(1, 22);
    bytes.writeUInt32LE(rate, 24); bytes.writeUInt32LE(rate * 2, 28); bytes.writeUInt16LE(2, 32); bytes.writeUInt16LE(16, 34);
    bytes.write('data', 36); bytes.writeUInt32LE(frames * 2, 40);
    let seed = 719 + index, phase = 0, low = 0, previous = 0, high = 0;
    for (let frame = 0; frame < frames; frame++) {
      const t = frame / rate;
      seed ^= seed << 13; seed ^= seed >>> 17; seed ^= seed << 5;
      const noise = (seed >>> 0) / 2147483648 - 1;
      low += 0.17 * (noise - low);
      high = 0.82 * (high + noise - previous); previous = noise;
      let value;
      if (name === 'bd' || name === 'tom') {
        phase += 2 * Math.PI * (name === 'bd' ? 48 + 145 * Math.exp(-t * 45) : 110 + 70 * Math.exp(-t * 30)) / rate;
        value = Math.sin(phase) * Math.exp(-t * (name === 'bd' ? 14 : 12)) + high * 0.12 * Math.exp(-t * 180);
      } else if (name === 'sd') {
        value = 0.65 * (noise - low) * Math.exp(-t * 24) + 0.35 * Math.sin(2 * Math.PI * 185 * t) * Math.exp(-t * 35);
      } else if (name === 'hh' || name === 'oh') {
        const metal = [4100, 5350, 6300, 7800].reduce((sum, hz) => sum + Math.sign(Math.sin(2 * Math.PI * hz * t)), 0) / 4;
        value = (0.65 * high + 0.35 * metal) * Math.exp(-t * (name === 'hh' ? 65 : 12));
      } else if (name === 'cp') {
        const burst = [0, 0.012, 0.024].reduce((sum, start) => sum + (t >= start ? Math.exp(-(t - start) * 150) : 0), 0);
        value = (noise - low) * (0.4 * burst + 0.35 * Math.exp(-t * 24));
      } else {
        value = (Math.sin(2 * Math.PI * 1750 * t) + 0.45 * Math.sin(2 * Math.PI * 2300 * t)) * Math.exp(-t * 85);
      }
      const fade = Math.min(1, t / 0.0005) * Math.min(1, (frames - 1 - frame) / 240);
      bytes.writeInt16LE(Math.round(Math.max(-1, Math.min(1, value * fade * 0.75)) * 32767), 44 + frame * 2);
    }
    return { name, label, durationSeconds, digest: crypto.createHash('sha256').update(bytes).digest('hex'), data: bytes.toString('base64') };
  });
  return { version: 1, provenance: 'Original procedural drum samples generated by scripts/generate-strudel-drums.cjs; GPL-3.0-or-later.', samples };
}
if (require.main === module) {
  const destination = path.join(__dirname, '../assets/strudel-drums/bank.json');
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.writeFileSync(destination, JSON.stringify(generateDrumBank(), null, 2) + '\n');
}
module.exports = { generateDrumBank };
